package io.github.ivangsa.gitpublisher.maven;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import javax.xml.parsers.DocumentBuilderFactory;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;

/**
 * Parameters of the {@code deploy} goal against the table in docs/design.md section 2 (Maven), read from the plugin
 * descriptor that maven-plugin-plugin generates (annotations are not visible at run time).
 */
class DeployMojoParametersTest {

    /** name -> {property, default}; a null default means none. */
    private static Map<String, String[]> designTable() {
        Map<String, String[]> table = new LinkedHashMap<>();
        table.put("repository", new String[] {"git-publisher.repository", null});
        table.put("branch", new String[] {"git-publisher.branch", "gh-pages"});
        table.put("nojekyll", new String[] {"git-publisher.nojekyll", "false"});
        table.put("serverId", new String[] {"git-publisher.serverId", null});
        table.put("keepSnapshots", new String[] {"git-publisher.keepSnapshots", "3"});
        table.put("keepVersions", new String[] {"git-publisher.keepVersions", "-1"});
        table.put("releaseRepository", new String[] {"git-publisher.releaseRepository", null});
        table.put("allowReleases", new String[] {"git-publisher.allowReleases", "false"});
        table.put("checksumAlgorithms", new String[] {"git-publisher.checksumAlgorithms", "SHA-1,MD5"});
        table.put("maxAttempts", new String[] {"git-publisher.maxAttempts", "5"});
        table.put("workDirectory", new String[] {
            "git-publisher.workDirectory", "${session.executionRootDirectory}/target/git-publisher"
        });
        table.put("dryRun", new String[] {"git-publisher.dryRun", "false"});
        table.put("skip", new String[] {"git-publisher.skip", "false"});
        table.put("commitAuthor", new String[] {
            "git-publisher.commitAuthor", "git-maven-publisher <git-maven-publisher@users.noreply.github.com>"
        });
        return table;
    }

    private static Element root;
    private static Element mojo;

    @BeforeAll
    static void readDescriptor() throws Exception {
        Path descriptor = Path.of("target", "classes", "META-INF", "maven", "plugin.xml");
        assertThat(descriptor).as("generated by maven-plugin-plugin in process-classes").exists();
        Document xml;
        try (var in = Files.newInputStream(descriptor)) {
            xml = DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(in);
        }
        root = xml.getDocumentElement();
        mojo = (Element) root.getElementsByTagName("mojo").item(0);
    }

    @Test
    void theDescriptorIdentifiesThePlugin() {
        assertThat(text(root, "groupId")).isEqualTo("io.github.ivangsa");
        assertThat(text(root, "artifactId")).isEqualTo("git-maven-publisher-maven-plugin");
        assertThat(text(root, "goalPrefix")).isNotBlank();
        assertThat(root.getElementsByTagName("mojo").getLength()).isEqualTo(1);
    }

    @Test
    void theGoalIsDeployBoundToTheDeployPhaseAndThreadSafe() {
        assertThat(text(mojo, "goal")).isEqualTo("deploy");
        assertThat(text(mojo, "phase")).isEqualTo("deploy");
        assertThat(text(mojo, "threadSafe")).isEqualTo("true");
    }

    @Test
    void everyDesignParameterIsEditableWithItsPropertyAndDefault() {
        Element configuration = (Element) mojo.getElementsByTagName("configuration").item(0);
        Map<String, Boolean> editable = editableParameters();
        for (Map.Entry<String, String[]> expected : designTable().entrySet()) {
            String name = expected.getKey();
            NodeList nodes = configuration.getElementsByTagName(name);
            assertThat(nodes.getLength()).as(name).isEqualTo(1);
            Element element = (Element) nodes.item(0);

            assertThat(editable).as(name + " editable").containsEntry(name, true);
            assertThat(element.getTextContent()).as(name + " property").isEqualTo("${" + expected.getValue()[0] + "}");
            String defaultValue = element.hasAttribute("default-value") ? element.getAttribute("default-value") : null;
            assertThat(defaultValue).as(name + " default").isEqualTo(expected.getValue()[1]);
        }
    }

    @Test
    void noParameterBeyondTheDesignIsUserConfigurableAndThereIsNoTokenParameter() {
        Map<String, Boolean> editable = editableParameters();

        assertThat(editable.entrySet().stream().filter(Map.Entry::getValue).map(Map.Entry::getKey))
                .containsExactlyInAnyOrderElementsOf(designTable().keySet());
        for (String name : editable.keySet()) {
            assertThat(name.toLowerCase()).doesNotContain("token", "password");
        }
    }

    private static Map<String, Boolean> editableParameters() {
        NodeList parameters = ((Element) mojo.getElementsByTagName("parameters").item(0)).getElementsByTagName("parameter");
        Map<String, Boolean> editable = new LinkedHashMap<>();
        for (int i = 0; i < parameters.getLength(); i++) {
            Element p = (Element) parameters.item(i);
            editable.put(text(p, "name"), Boolean.parseBoolean(text(p, "editable")));
        }
        return editable;
    }

    private static String text(Element parent, String tag) {
        NodeList nodes = parent.getElementsByTagName(tag);
        return nodes.getLength() == 0 ? "" : nodes.item(0).getTextContent().trim();
    }
}
